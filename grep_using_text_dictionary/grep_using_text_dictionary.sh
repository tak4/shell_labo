#!/bin/bash

word_file="search_dict.txt"
target_dir="."

# IFS= : 区切り文字指定 指定無しなので、空白文字を区切り文字としない。
#        つまり、行頭・行末の空白やバックスラッシュを変換する。
# -r   : \ を特殊文字とせず、そのままkeywordに格納する。
# --   : コマンドライン引数の「オプションはここまで」という区切り。
#        対象ファイル名が -data.txt でも、grep のオプションと誤解されない。
while IFS= read -r keyword || [[ -n "$keyword" ]]; do
  [[ -z "$keyword" ]] && continue
  find "$target_dir" -type f -exec grep -nH -e "$keyword" -- {} +
done < "$word_file"


# find：ファイルやディレクトリを検索するコマンドです。
# "$target_dir"：検索を始めるディレクトリです。ダブルクォートにより、パスに空白があってもひとつの引数として扱います。
# -type f：通常ファイルだけを対象にします。ディレクトリなどは除外します。
# -exec ...：見つかったファイルに対して、指定したコマンドを実行します。
# grep：ファイル内から検索語に一致する行を探します。
# -n：一致した行の行番号を表示します。
# -H：結果にファイル名を表示します。
# -e "$keyword"：$keyword を検索パターンとして指定します。-e により、検索語が - で始まってもオプションと誤認されません。
# --：grep のオプションはここまで、と示します。以降の引数をオプションではなくファイル名として扱わせます。
# {}：find が見つけたファイル名に置き換わります。
# +：見つかったファイル名をまとめて grep に渡します。ファイルごとに grep を起動する \; より効率的です。
